#!/usr/bin/env python3
"""Regenerate the inventory block in modules/README.md from the modules themselves.

That README opened with "Fourteen of them, 156 features, 2,803 alignments" long
after the directory held 46 modules, because the count was prose someone had to
remember to edit. It had drifted twice. The prose below the block is worth
keeping and is left exactly as it is; only the table and its totals are
generated, between the INVENTORY markers.

    python3 skill/scripts/gen_modules_readme.py [--check]

--check exits 1 if the file on disk is not what this would write, so CI or a
pre-commit hook can refuse a stale README.
"""
import argparse
import glob
import json
import os
import sys

BEGIN = "<!-- INVENTORY:BEGIN -- generated by skill/scripts/gen_modules_readme.py -->"
END = "<!-- INVENTORY:END -->"

#  Modules whose shape needs a word of explanation. Anything not named here is
#  described by its numbers alone.
NOTES = {
    "Alpharhabdovirinae": "largest module in the kit",
    "Allexivirus": "TGB3 `upstream_ext: 0`, non-AUG (CUG) start",
    "Alphaflexiviridae": "Potexvirus + Lolavirus; split from Allexivirus over TGB3",
    "Tobamovirus": "REP183 readthrough (`internal_stop`)",
    "Hepaciviridae": "hepatitis C; `F` is `transcript_edit` (+1 frameshift)",
    "Orthoflavivirus": "15-product polyprotein; `NS1P` `transcript_edit`",
    "Togaviridae": "`TF` `transcript_edit`",
    "Cardiovirus": "`2B*` `transcript_edit`",
    "Merhavirus": "`L_SPLICED` splice",
    "HIV1": "`TAT`/`REV` splice at `splice_id: 85`; POL starts at the frameshift, not a Met",
    "Coltivirus": "segment 9 bicistronic by stop-codon read-through",
    "Rotavirus": "VP8*/VP5* cut from VP4 by motif; species A only",
    "PiscineOrthoreovirus": "S1 bicistronic, p13 nested inside sigma3",
}


def inventory(root):
    rows, tot = [], dict(f=0, a=0, r=0)
    for d in sorted(os.listdir(root), key=str.lower):
        p = os.path.join(root, d)
        j = os.path.join(p, "%s_Viral_PSSM.json" % d)
        if not os.path.isdir(p) or not os.path.exists(j):
            continue
        block = json.load(open(j))[d]
        nf = len(block.get("features", {}))
        na = len(glob.glob(os.path.join(p, "PSSM-Alignments", "*", "corrected_alis", "*.fa")))
        nr = len(glob.glob(os.path.join(p, "Rep-Contigs", "*.dna")))
        special = []
        if glob.glob(os.path.join(p, "Splice-Variants", "*.fasta")):
            special.append("splice refs")
        if glob.glob(os.path.join(p, "Transcript-Editing", "*.fasta")):
            special.append("transcript-edit refs")
        rows.append((d, nf, na, nr, NOTES.get(d, ""), special))
        tot["f"] += nf
        tot["a"] += na
        tot["r"] += nr
    return rows, tot


def render(rows, tot):
    o = [BEGIN, "",
         "Every module built with this kit: **%d of them, %d features, %s alignments,"
         % (len(rows), tot["f"], "{:,}".format(tot["a"])),
         "%s rep contigs.**" % "{:,}".format(tot["r"]), "",
         "The alignments are the provenance and the profiles are derived from them,",
         "so the counts below are of alignments; a module's profile count equals its",
         "alignment count by construction.", "",
         "| module | features | alignments | rep contigs | notes |",
         "|---|---|---|---|---|"]
    for d, nf, na, nr, note, special in rows:
        bits = [b for b in ([note] if note else []) + special if b]
        o.append("| `%s` | %d | %d | %d | %s |" % (d, nf, na, nr, "; ".join(bits)))
    o += ["", END]
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    kit = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    readme = os.path.join(kit, "modules", "README.md")
    text = open(readme).read()
    if BEGIN not in text or END not in text:
        print("markers missing in %s -- add %s / %s around the table" % (readme, BEGIN, END))
        return 1
    rows, tot = inventory(os.path.join(kit, "modules"))
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + render(rows, tot) + tail
    if a.check:
        ok = new == text
        print("modules/README.md is %s" % ("current" if ok else "STALE -- re-run without --check"))
        return 0 if ok else 1
    open(readme, "w").write(new)
    print("modules/README.md: %d modules, %d features, %d alignments, %d rep contigs"
          % (len(rows), tot["f"], tot["a"], tot["r"]))
    return 0


sys.exit(main())
