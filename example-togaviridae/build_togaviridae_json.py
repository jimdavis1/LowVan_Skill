# ==========================================================================
# FEATURES CALLED BY AN EXTERNAL PROGRAM
#
# TF is made by a -1 ribosomal frameshift at a conserved UUUUUUA heptamer
# inside 6K (Firth 2008), so it is not collinear with the genome in any single
# frame and no PSSM can call it: tblastn splits a TF query into two HSPs in
# frames 1 and 3. get_transcript_edited_features.pl handles it instead, by
# blastn-ing a curated nucleotide reference that carries one extra templated
# base and filling the resulting subject gap from the query.
#
# Note that "transcript_edit" is the kit's mechanism, not a claim about the
# biology. A paramyxovirus V mRNA really does differ from its template -- the
# polymerase inserts a non-templated G. Nothing edits the alphavirus message;
# the ribosome re-reads one templated base. The two are informationally
# identical, which is why the same machinery serves both, but there is no such
# thing as an edited alphavirus transcript to go looking for.
#
# mat_peptide, not CDS: TF has no initiating Met. Its N-terminus is made by
# signal peptidase at the E2/6K junction -- the same cut that makes 6K's -- so
# the reference starts GCC, exactly as the coronavirus NSP12 references start
# TCA/AGT. Its C-terminus, unlike NSP12's, IS a stop codon, so the reference
# keeps it and the protein carries a trailing "*" -- the ssGP convention, and
# the same thing the scan-to-stop features (nsP1234, STP, nsP4, E1) do.
# min/max span the 62-100 residues observed across 234 constructed references;
# 76 is the mode (151 of 234) and the divergent salmonid alphaviruses hold the
# long tail at 93-100.
# ==========================================================================
