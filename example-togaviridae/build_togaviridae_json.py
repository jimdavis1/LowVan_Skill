#!/usr/bin/env python3
"""Generate the Togaviridae block of Viral_PSSM.json.

Everything here is derived from files in this directory, so the JSON can be
regenerated byte-identically after any rebuild:

    collections/report.tsv     length bounds
    cutoff_measurements.json   the signal/noise window each bit_cutoff sits in
    rep_contigs.json           close_genomes
    Alignments/<M>/<F>/pssms/  which features actually have profiles

Written in the canonical format -- JSON::XS pretty + canonical: 3-space indent,
" : " between key and value, keys sorted at every level -- so a Perl tool
rewriting the master produces no spurious diff.
"""
import glob, json, os, sys

MOD = "Togaviridae"

# ==========================================================================
# ANNOTATION STRINGS
# ==========================================================================
# Two are REUSED verbatim from the controlled vocabulary rather than coined:
#
#   RNA-dependent RNA polymerase   for nsP4. Already carried by 12 taxa, and
#                                  used for a mat_peptide by the coronavirus
#                                  modules (NSP12), so the precedent for a
#                                  cleavage product carrying it exists.
#   Nucleocapsid protein           for C. The alphavirus capsid binds the
#                                  genome and forms the nucleocapsid core;
#                                  coining "Capsid protein" beside the existing
#                                  string would add a vocabulary entry for a
#                                  protein the vocabulary already names.
#
# Nine are new. Each one says only what the SOURCE DATA already asserts, which
# is the rule for a functional claim with no DLIT a human has read:
#
#   nsP1  BV-BRC says "mRNA-capping enzyme nsp1" on 7,384 features, so the
#         capping claim is the submitters', not ours.
#   nsP2  BV-BRC says "protease nsp2" on 8,255 features. nsP2 is also an RNA
#         helicase, NTPase and RNA triphosphatase and is the transcriptional
#         shutoff factor, but none of that is in the source and all of it would
#         rest on citations nobody here has read -- so the string stays at
#         "Protease". The helicase PMIDs ride along on the feature, flagged, so
#         a curator can promote the name later.
#   nsP3  BV-BRC says only "non-structural protein nsp3". The macrodomain,
#         zinc-binding domain and hypervariable host-factor-binding domain are
#         all real and all absent from the source, so the annotation makes no
#         functional claim at all. Same reasoning, same remedy.
#   E1/E2/E3  "Mature envelope glycoprotein E<n>". E1 is the class II fusion
#         protein and E2 carries the receptor-binding site; neither claim is in
#         the source, and "Mature C-terminal envelope glycoprotein Gc" in the
#         vocabulary shows that a positional/symbolic form without a functional
#         claim is the house style for a cleaved envelope product.
#   6K    the source's own words, in the vocabulary's "Mature " form. 6K's
#         viroporin activity is documented but, again, not by anything read
#         here.
#   P1234 / SP  the two precursors, named as the vocabulary names precursors
#         ("ORF1ab polyprotein", "Pre-glycoprotein polyprotein GP complex").
#         NOTE the nonstructural one is "Nonstructural polyprotein" and NOT
#         "... P1234" -- see THE OPAL CODON below. Naming it P1234 would be
#         wrong on seven alphaviruses in eight.
#
# No taxon prefix on any of them: the current vocabulary revision removed those.
# ==========================================================================
